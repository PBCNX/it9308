"""Generate it9308/sequence.py from the captured vendor bring-up.

The captures are observation logs (timestamp + transmitted frame). This script
keeps only what a driver needs: delay, frame, and how many response bytes the
command expects.
"""
import os
import re

ROOT = r"D:\Profile\Documents\DeepSeek\sticks"
OUT = os.path.join(ROOT, "it9308", "it9308", "sequence.py")
STAMP = re.compile(r"(\d{2}):(\d{2}):(\d{2})\.(\d{3})")
FRAME = re.compile(r"TX\s+(-?\d+)\s+([0-9a-f]+)")


def reply_len(frame):
    cmd = (frame[1] << 8) | frame[2]
    payload = frame[4:-2]
    if cmd in (0x00, 0x2A) and payload:
        return payload[0]
    if cmd == 0x22:
        return 4
    return 0


steps = []
for name in ("capture1.txt", "capture2.txt"):
    last = None
    for line in open(os.path.join(ROOT, ".tmp", name), encoding="utf-8", errors="replace"):
        m = FRAME.search(line)
        if not m:
            continue
        s = STAMP.search(line)
        stamp = None
        if s:
            h, mi, sec, ms = (int(x) for x in s.groups())
            stamp = h * 3600 + mi * 60 + sec + ms / 1000.0
        frame = bytes.fromhex(m.group(2))
        delay = 0
        if last is not None and stamp is not None:
            delay = int(min(max(stamp - last, 0.0), 0.5) * 1000)
        if stamp is not None:
            last = stamp
        steps.append((delay, frame.hex(), reply_len(frame)))
    steps.append((200, None, 0))   # gap between the two captured sessions

lines = ["# Generated by tools/gen_sequence.py -- captured vendor bring-up.",
         "# Each step: (delay_ms, frame_hex, reply_bytes).",
         "STEPS = ["]
for delay, frame, reply in steps:
    if frame is None:
        lines.append("    (%d, None, %d)," % (delay, reply))
    else:
        lines.append('    (%d, "%s", %d),' % (delay, frame, reply))
lines.append("]")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("wrote", OUT, len(steps), "steps")
